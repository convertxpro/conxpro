export const ALL_TOOLS: ToolMetadata[] = CATEGORIES.flatMap((category) => category.tools);

export function getToolBySlug(categorySlug: string, slug: string): ToolMetadata | undefined {
  // 1. Direct exact match
  const exact = ALL_TOOLS.find((t) => t.categorySlug === categorySlug && t.slug === slug);
  if (exact) return exact;

  // 2. Media / Video / Audio cross-alias match
  if (categorySlug === 'media' || categorySlug === 'video' || categorySlug === 'audio') {
    return ALL_TOOLS.find(
      (t) =>
        (t.categorySlug === 'video' || t.categorySlug === 'audio' || t.categorySlug === 'media') &&
        t.slug === slug
    );
  }

  return undefined;
}

export function getCategoryBySlug(slug: string): CategoryMetadata | undefined {
  const found = CATEGORIES.find((c) => c.slug === slug);
  if (found) return found;

  // Media fallback to video category
  if (slug === 'media') {
    return CATEGORIES.find((c) => c.slug === 'video');
  }

  return undefined;
}
